create table if not exists public.equipamentos_mina (
  id bigint generated by default as identity primary key,
  nome text not null,
  status text not null,
  causa text,
  descricao text,
  hora_inicio text,
  hora_fim text,
  data_hora_cadastro text,
  created_at timestamptz not null default now()
);

alter table public.equipamentos_mina enable row level security;

create policy "read equipamentos"
on public.equipamentos_mina
for select
using (true);

create policy "insert equipamentos"
on public.equipamentos_mina
for insert
with check (true);

create policy "update equipamentos"
on public.equipamentos_mina
for update
using (true)
with check (true);

create policy "delete equipamentos"
on public.equipamentos_mina
for delete
using (true);
